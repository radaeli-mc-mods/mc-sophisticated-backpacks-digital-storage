"""Generates the feeding upgrade refresh candidates and a comparison sheet."""
import sys
from pathlib import Path
from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[2]
OUT = Path(__file__).resolve().parent

H = lambda s: tuple(int(s[i:i + 2], 16) for i in (1, 3, 5)) + (255,)

# Shared body (SCC-inspired slate) and screen (the line's green display).
OUTLINE, BEZEL, BEZEL_HI, BEZEL_LO = H("#0e1119"), H("#3a4656"), H("#566679"), H("#283140")
SCREEN, SCREEN_SHADE = H("#37ae6c"), H("#2f9a5f")
# One accent per supported network: (light, mid, dark).
AE2 = (H("#d2b4ff"), H("#8f62e6"), H("#583a9c"))   # fluix
RS = (H("#9edcff"), H("#3d9ae2"), H("#22609b"))    # light-blue controller
TSS = (H("#d6a868"), H("#a6763f"), H("#6c4b27"))   # oak terminal
SCC = (H("#ffdf82"), H("#ffc62e"), H("#b8720c"))   # gold trim, from SCC branding

# The in-game texture is regenerated by export_feeding.py, so the icon always comes from the original.
src = Image.open(OUT / "remote_feeding_upgrade_original.png").convert("RGBA")
FIELD = src.getpixel((3, 3))
icon = {(x, y): src.getpixel((x, y)) for x in range(3, 13) for y in range(3, 13)
        if src.getpixel((x, y)) != FIELD}


def base():
    im = Image.new("RGBA", (16, 16), (0, 0, 0, 0))
    px = im.load()
    for i in range(1, 15):
        for e in ((i, 1), (i, 14), (1, i), (14, i)):
            px[e] = OUTLINE
    for i in range(2, 14):
        px[i, 2] = BEZEL_HI
        px[2, i] = BEZEL_HI
        px[i, 13] = BEZEL_LO
        px[13, i] = BEZEL_LO
    px[13, 2] = px[2, 13] = BEZEL
    for x in range(3, 13):
        for y in range(3, 13):
            px[x, y] = SCREEN_SHADE if x == 3 or y == 3 else SCREEN
    return im, px


def stamp_icon(px):
    for p, c in icon.items():
        px[p] = c


def paint_corner(px, corner, colors):
    (cx, cy, dx, dy), (lt, mid, dk) = corner, colors
    px[cx, cy] = mid
    px[cx + dx, cy] = mid
    px[cx, cy + dy] = mid
    px[cx + 2 * dx, cy] = dk
    px[cx, cy + 2 * dy] = dk
    px[cx + dx, cy + dy] = lt


CORNERS = [(1, 1, 1, 1), (14, 1, -1, 1), (1, 14, 1, -1), (14, 14, -1, -1)]
# Top-left AE2, top-right SCC, bottom-left TSS, bottom-right RS.
CORNER_COLORS = [AE2, SCC, TSS, RS]


def paint_corners(px):
    for corner, colors in zip(CORNERS, CORNER_COLORS):
        paint_corner(px, corner, colors)


def corners():
    im, px = base()
    paint_corners(px)
    stamp_icon(px)
    return im
NETWORKS = {"ae2": AE2, "rs": RS, "tss": TSS, "scc": SCC}


def linked(network):
    """Direction A once linked: the whole rim takes the network's color."""
    lt, mid, dk = NETWORKS[network]
    im, px = base()
    for i in range(1, 15):
        px[i, 1] = px[1, i] = mid
        px[i, 14] = px[14, i] = dk
    for cx, cy, dx, dy in CORNERS:
        px[cx + dx, cy + dy] = lt
    stamp_icon(px)
    return im


SCREENS = {"dark": (H("#161b25"), H("#10141c")), "light": (H("#e2e7ee"), H("#cbd3dc"))}
OUTLINE_PX, FILL_PX, HIGHLIGHT_PX = src.getpixel((7, 6)), src.getpixel((9, 5)), src.getpixel((8, 6))


def linked_icon(network, screen="dark"):
    """Direction A once linked: plain frame, contrasting screen, icon in the network's color."""
    lt, mid, dk = NETWORKS[network]
    face, shade = SCREENS[screen]
    im, px = base()
    for x in range(3, 13):
        for y in range(3, 13):
            px[x, y] = shade if x == 3 or y == 3 else face
    recolor = {OUTLINE_PX: dk, FILL_PX: mid, HIGHLIGHT_PX: lt}
    for p, c in icon.items():
        px[p] = recolor.get(c, c)
    return im


def linked_final(network):
    """Dark screen and network-colored icon; the four network corners stay."""
    im = linked_icon(network, "dark")
    paint_corners(im.load())
    return im


def strip():
    im, px = base()
    for i, (lt, mid, dk) in enumerate([AE2, RS, TSS, SCC]):
        for k in range(3):
            x = 2 + i * 3 + k
            px[x, 1] = lt if k == 1 else mid
    stamp_icon(px)
    return im


def leds():
    im, px = base()
    for x, (lt, mid, dk) in zip((4, 6, 9, 11), [AE2, RS, TSS, SCC]):
        px[x, 13] = lt
        px[x, 14] = dk
    stamp_icon(px)
    return im


def heritage():
    """Original Sophisticated frame; each yellow corner becomes one network."""
    im = src.copy()
    px = im.load()
    yellow = src.getpixel((1, 1))
    for (x0, y0), (lt, mid, dk) in zip([(1, 1), (12, 1), (1, 12), (12, 12)], [AE2, RS, TSS, SCC]):
        for x in range(x0, x0 + 3):
            for y in range(y0, y0 + 3):
                if px[x, y] == yellow:
                    px[x, y] = mid
        corner = (1 if x0 == 1 else 14, 1 if y0 == 1 else 14)
        px[corner] = lt
    return im


CANDIDATES = {"A_corners": corners(), "B_strip": strip(), "C_leds": leds(), "D_heritage": heritage()}


def slot(im, scale):
    """Inventory-slot mockup at a GUI scale."""
    s = 18 * scale
    bg = Image.new("RGBA", (s, s), H("#8b8b8b"))
    d = ImageDraw.Draw(bg)
    d.rectangle((0, 0, s - 1, scale - 1), fill=H("#373737"))
    d.rectangle((0, 0, scale - 1, s - 1), fill=H("#373737"))
    d.rectangle((0, s - scale, s - 1, s - 1), fill=H("#ffffff"))
    d.rectangle((s - scale, 0, s - 1, s - 1), fill=H("#ffffff"))
    big = im.resize((16 * scale, 16 * scale), Image.NEAREST)
    bg.alpha_composite(big, (scale, scale))
    return bg


def sheet(items=None):
    items = items or [("current", src)] + list(CANDIDATES.items())
    big, gap = 12, 24
    col = 16 * big + gap
    W = col * len(items) + gap
    sheet = Image.new("RGBA", (W, 16 * big + 18 * 3 + gap * 3), H("#1b1d22"))
    for i, (_, im) in enumerate(items):
        x = gap + i * col
        sheet.alpha_composite(im.resize((16 * big, 16 * big), Image.NEAREST), (x, gap))
        sheet.alpha_composite(slot(im, 3), (x, gap * 2 + 16 * big))
        sheet.alpha_composite(slot(im, 1), (x + 18 * 3 + 12, gap * 2 + 16 * big))
    return sheet


if __name__ == "__main__":
    for name, im in CANDIDATES.items():
        im.save(OUT / f"remote_feeding_upgrade_{name}.png")
    sheet().save(OUT / "feeding_comparison.png")
    linked_items = [("unlinked", CANDIDATES["A_corners"])] + [(n, linked(n)) for n in NETWORKS]
    for name, im in linked_items[1:]:
        im.save(OUT / f"remote_feeding_upgrade_A_linked_{name}.png")
    sheet(linked_items).save(OUT / "feeding_A_linked.png")
    for screen in SCREENS:
        items = [("unlinked", CANDIDATES["A_corners"])] + [(n, linked_icon(n, screen)) for n in NETWORKS]
        for name, im in items[1:]:
            im.save(OUT / f"remote_feeding_upgrade_A_icon_{screen}_{name}.png")
        sheet(items).save(OUT / f"feeding_A_icon_{screen}.png")
    items = [("unlinked", CANDIDATES["A_corners"])] + [(n, linked_final(n)) for n in NETWORKS]
    for name, im in items[1:]:
        im.save(OUT / f"remote_feeding_upgrade_A_final_{name}.png")
    sheet(items).save(OUT / "feeding_A_final.png")
    print("ok")
